from typing import Protocol
from torch import Tensor
from torch.distributions import Distribution

class Policy(Protocol):
    """Native action/value contract consumed by collection, update and evaluation."""
    def act(self, obs: Tensor) -> tuple[Tensor,Tensor,Tensor]: ...
    def evaluate(self, obs: Tensor, actions: Tensor) -> tuple[Tensor,Tensor,Tensor]: ...
    def predict_value(self, obs: Tensor) -> Tensor: ...
    def dist(self, obs: Tensor) -> Distribution: ...

class AdvantagePolicy(Policy, Protocol):
    def advantages(self, obs: Tensor, probabilities: Tensor) -> Tensor: ...

class RelativeValuePolicy(Policy, Protocol):
    def relative_value(self, first: Tensor, second: Tensor) -> Tensor: ...
